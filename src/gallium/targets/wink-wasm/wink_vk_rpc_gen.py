"""Generate main-thread Vulkan dispatch for Wink's shared-memory browser mode.

Only wrap functions actually returned by the driver. Arguments live on the
waiting caller's stack; pointees are shared Wasm memory, as for the GL RPCs.
No process-wide instance/device is substituted for the caller's handles.
"""
import re
import sys


def generate(header):
    protos = re.findall(r"VKAPI_ATTR\s+(\w[\w\s\*]*?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\);", header, re.S)
    functions = {}
    for ret, name, params in protos:
        functions[name] = (' '.join(ret.split()), ' '.join(params.split()))
    lines = ['/* Generated by wink_vk_rpc_gen.py. */',
             'static PFN_vkVoidFunction wink_vk_rpc_wrap(const char *, PFN_vkVoidFunction);',
             f'static uintptr_t wink_vk_rpc_targets[{len(functions)}];']
    for index, (name, (ret, params)) in enumerate(functions.items()):
        fields, names = [], []
        for param in ([] if params == 'void' else params.split(',')):
            match = re.search(r'(\w+)\s*(\[[^\]]*\])?\s*$', param)
            if not match:
                raise ValueError(f'unrecognized parameter: {name}: {param}')
            arg = match.group(1)
            names.append(arg)
            fields.append(re.sub(r'(\w+)\s*\[[^\]]*\]$', r'*\1', param.strip()) + ';')
        tag = 'wink_vk_rpc_' + name
        lines += [f'struct {tag}_args {{']
        lines += ['   ' + field for field in fields]
        if ret != 'void':
            lines += [f'   {ret} result;']
        lines += ['};', f'static void {tag}_call(void *data) {{',
                  f'   struct {tag}_args *a = data;',
                  f'   PFN_{name} fn = (PFN_{name})p_atomic_read(&wink_vk_rpc_targets[{index}]);']
        call = f'fn({", ".join("a->" + arg for arg in names)})'
        lines += ['   ' + (call + ';' if ret == 'void' else 'a->result = ' + call + ';')]
        if name in ('vkGetInstanceProcAddr', 'vkGetDeviceProcAddr'):
            lines += ['   a->result = wink_vk_rpc_wrap(a->pName, a->result);']
        lines += ['}', f'static VKAPI_ATTR {ret} VKAPI_CALL {tag}({params}) {{',
                  f'   struct {tag}_args a = {{' + ', '.join('.' + arg + ' = ' + arg for arg in names) + '};']
        if name in ('vkWaitForFences', 'vkWaitSemaphores', 'vkWaitSemaphoresKHR'):
            # A queued infinite wait must not hold up a signal/submission from
            # another worker. Return to the runner between nonblocking polls.
            lines += ['   if (!emscripten_is_main_browser_thread()) {',
                      '      const uint64_t start = os_time_get_nano();',
                      '      a.timeout = 0;', '      for (;;) {',
                      f'         wink_rpc({tag}_call, &a);',
                      '         if (a.result != VK_TIMEOUT ||',
                      '             (uint64_t)os_time_get_nano() - start >= timeout)',
                      '            return a.result;',
                      '         os_time_sleep(1000);', '      }', '   }']
        lines += [f'   wink_rpc({tag}_call, &a);']
        if ret != 'void':
            lines += ['   return a.result;']
        lines += ['}']
    lines += ['static PFN_vkVoidFunction',
              'wink_vk_rpc_wrap(const char *name, PFN_vkVoidFunction actual) {',
              '   if (!actual) return NULL;']
    for index, name in enumerate(functions):
        lines += [f'   if (!strcmp(name, "{name}")) {{',
                  f'      p_atomic_set(&wink_vk_rpc_targets[{index}], (uintptr_t)actual);',
                  f'      return (PFN_vkVoidFunction)wink_vk_rpc_{name};', '   }']
    lines += ['   return actual;', '}']
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    with open(sys.argv[1]) as source, open(sys.argv[2], 'w') as output:
        output.write(generate(source.read()))

   "  writing = true;\n"
   "  point_base = counts[p.patches * 2u + patch_index * 2u];\n"
   "  index_base = counts[p.patches * 2u + patch_index * 2u + 1u];\n"
   "  tessellate(patch_index);\n"
   "}\n";

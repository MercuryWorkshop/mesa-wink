# A Vulkan "loader" for tests that link wink: every vk* function in
# vulkan_core.h, resolved on first call through wink_vk_get_instance_proc_addr.
# The driver's vkGetInstanceProcAddr gives out device-level trampolines too,
# so one instance is all it needs -- the one vkCreateInstance last made.
#
#   gen-shim.py <vulkan_core.h> <out.c>
import re
import sys

header, out = sys.argv[1], sys.argv[2]
text = open(header).read()
protos = re.findall(r'VKAPI_ATTR\s+(\w[\w\s\*]*?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\);', text, re.S)

lines = [
    '/* Generated by gen-shim.py. */',
    '#include <vulkan/vulkan_core.h>',
    '#include <stddef.h>',
    '',
    'typedef void (*wink_vk_void_function)(void);',
    'wink_vk_void_function wink_vk_get_instance_proc_addr(void *instance, const char *name);',
    '',
    'static VkInstance shim_instance;',
    '',
    'static PFN_vkVoidFunction',
    'resolve(const char *name)',
    '{',
    '   return (PFN_vkVoidFunction)wink_vk_get_instance_proc_addr(shim_instance, name);',
    '}',
    '',
]
seen = set()
for ret, name, params in protos:
    if name in seen:
        continue
    seen.add(name)
    ret = ' '.join(ret.split())
    params = ' '.join(params.split())
    names = []
    if params != 'void':
        for p in params.split(','):
            m = re.search(r'(\w+)\s*(\[[^\]]*\])?\s*$', p.strip())
            names.append(m.group(1))
    call = f'p({", ".join(names)})'
    body = [f'   static PFN_{name} p;', f'   if (!p)', f'      p = (PFN_{name})resolve("{name}");']
    if name == 'vkCreateInstance':
        body += ['   VkResult r = p(pCreateInfo, pAllocator, pInstance);',
                 '   if (r == VK_SUCCESS)', '      shim_instance = *pInstance;', '   return r;']
    elif name == 'vkGetInstanceProcAddr':
        body = ['   return resolve(pName);']
    elif ret == 'void':
        body.append(f'   {call};')
    else:
        body.append(f'   return {call};')
    lines += [f'VKAPI_ATTR {ret} VKAPI_CALL', f'{name}({params})', '{'] + body + ['}', '']
open(out, 'w').write('\n'.join(lines))
